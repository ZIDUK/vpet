def validate(items=ITEMS):
    required = {"id", "category", "rarity", "icon", "names", "descriptions", "stack_max",
                "effects", "target", "magnitude", "duration", "limits", "source"}
    assert len({i["id"] for i in items}) == len(items), "duplicate IDs"
    assert len({i["index"] for i in items}) == len(items), "duplicate slots"
    for item in items:
        assert required <= set(item), "incomplete item definition"
        assert item["category"] in CATEGORIES, "unsupported category (evolution excluded)"
        assert item["index"] != 6, "BACK is navigation, not an item"
        assert item["unlimited"] or 0 <= item["initial_stock"] <= item["stack_max"]
        for language in ("ES", "EN"):
            assert item["names"][language] and item["descriptions"][language]
        for effect in item["effects"]:
            assert effect["kind"] in ("restore", "weight", "effort", "ev", "mood", "heal_injury", "training_ev_bonus"), "unsupported effect (evolution excluded)"
            assert effect["target"] in ("h", "e", "weight", "hp", "mp", "off", "def", "spd", "brn", "p", "effort", "injured", "trained_stat"), "unsupported target (evolution excluded)"
            assert 0 < effect["amount"] <= effect["cap"]


def cpp_header():
    quote = lambda value: json.dumps(value, ensure_ascii=True)
    lines = ["// Generated by scripts/export_item_catalog.py; edit core/item_catalog.py.",
             "#pragma once", "#include <stdint.h>", "namespace vpet { namespace items {",
             "static constexpr uint8_t kCatalogVersion = %d;" % CATALOG_VERSION,
             "static constexpr uint8_t kStackMax = %d;" % max(i["stack_max"] for i in ITEMS if i["stack_max"] is not None),
             "struct Definition {", "    const char* id; uint8_t index;",
             "    const char* es; const char* en; const char* blurbEs; const char* blurbEn;",
             "    const char* icon; const char* category; const char* rarity; const char* duration;",
             "    const char* source; int16_t stackMax; uint8_t initialStock; bool firmwareAvailable;",
             "};", "static constexpr Definition kCatalog[] = {"]
    for item in ITEMS:
        values = [quote(item["id"]), str(item["index"]),
                  quote(item["names"]["ES"]), quote(item["names"]["EN"]),
                  quote(item["blurbs"]["ES"]), quote(item["blurbs"]["EN"]),
                  quote("/ui/icons/" + item["icon"].lower() + ".vpa"),
                  quote(item["category"]), quote(item["rarity"]), quote(item["duration"]),
                  quote(item["source"]), str(item["stack_max"] if item["stack_max"] is not None else -1),
                  str(item["initial_stock"]), "true" if item["firmware_available"] else "false"]
        lines.append("    {" + ", ".join(values) + "},")
    lines += ["};", "inline const Definition* at(uint8_t index) {",
              "    for (const auto& item : kCatalog) if (item.index == index) return &item;",
              "    return nullptr;", "}"]
    for name, item_id, kind, target in CONSTANTS:
        lines.append("static constexpr uint8_t %s = %d;" % (name, effect_amount(item_id, kind, target)))
    lines += ["} }  // namespace vpet::items", ""]
    return "\n".join(lines)


