def export(root=ROOT, check=False):
    validate()
    root = Path(root)
    for relative, content in ((HEADER, cpp_header()), (DOC, markdown())):
        path = root / relative
        if check:
            if not path.exists() or path.read_text() != content:
                raise ValueError("Outdated catalog artifact: " + str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    for item in ITEMS:
        path = root / SPRITES / (item["id"] + ".png")
        image = render_item_icon(item["icon"], 32, framed=False)
        if check:
            with Image.open(path) as existing:
                if existing.convert("RGBA").tobytes() != image.tobytes():
                    raise ValueError("Outdated sprite: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            image.save(path)


def gallery(root=ROOT):
    output = Path(root) / "out" / "item-catalog"
    output.mkdir(parents=True, exist_ok=True)
    sheet = Image.new("RGB", (7 * 144, 192), (16, 22, 26))
    draw = ImageDraw.Draw(sheet)
    for i, item in enumerate(ITEMS):
        image = render_item_icon(item["icon"], 96, framed=False)
        sheet.paste(image, (i * 144 + 24, 20), image)
        draw.text((i * 144 + 24, 130), item["names"]["ES"], fill=(255, 217, 61))
        draw.text((i * 144 + 24, 147), item["names"]["EN"], fill=(234, 238, 219))
        draw.text((i * 144 + 24, 165), item["id"], fill=(156, 178, 179))
    sheet.save(output / "sprites.png")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    export(check=args.check)
    if not args.check:
        gallery()
    print("Official item catalog v%d: %d items; evolution items excluded." % (CATALOG_VERSION, len(ITEMS)))
