"""Validate builtin content and generate portable lookup tables, not an installer."""
import argparse
import json
import pprint
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))
from core.content import ACTIONS, CONTEXTS, LEGACY_ROLES, PetDefinition

SOURCE = Path("src/data/content/firemon.json")
HEADER = Path("firmware/t-display/lib/vpet_core/src/vpet/BuiltinPet.generated.h")
PYTHON = Path("src/core/content_builtin.py")
RULE_HEADER = Path("firmware/t-display/lib/vpet_core/src/vpet/EvolutionRules.generated.h")
RULE_PYTHON = Path("src/core/rules_builtin.py")


def load_definition(path=ROOT / SOURCE):
    source = Path(path)
    if source.stat().st_size > 65536:
        raise ValueError("Content definition exceeds 64 KiB")
    def unique_pairs(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError("Duplicate content key: " + key)
            result[key] = value
        return result
    return PetDefinition(json.loads(source.read_text(), object_pairs_hook=unique_pairs))


def rules_registry():
    fields = ("evolves_to", "automatic", "requirements_pending", "min_stage_age_seconds",
              "max_care_mistakes", "battles_required", "requirements", "min_weight", "max_weight")
    rules = {}
    for role in ("baby", "rookie", "champion"):
        source = json.loads((ROOT / "src/data/digimon" / (role + ".json")).read_text())
        rules[role] = {key: source[key] for key in fields if key in source}
    return rules


def rules_header():
    names = dict(zip(LEGACY_ROLES, ("Rookie", "Champion", "Ultimate", "Egg", "Baby")))
    lines = ["// Generated by scripts/content_definitions.py; edit src/data/digimon/*.json.",
             "#pragma once", "namespace vpet { namespace rules {",
             "static constexpr EvolutionRule kEvolutionRules[] = {"]
    for role, rule in rules_registry().items():
        bars = rule.get("requirements", {})
        values = ["SpeciesId::" + names[role], "SpeciesId::" + names[rule["evolves_to"]],
                  str(rule.get("automatic", True)).lower(), str(rule.get("requirements_pending", False)).lower(),
                  *map(str, (rule.get("min_stage_age_seconds", 0), rule.get("max_care_mistakes", -1),
                             rule.get("battles_required", 0), *[bars.get(k, 0) for k in ("h", "e", "p", "hp")],
                             rule.get("min_weight", 0), rule.get("max_weight", 0)))]
        lines.append("    {%s}," % ",".join(values))
    return "\n".join(lines + ["};", "} }", ""])


def validate_art(definition, build_dir):
    root = Path(build_dir).resolve()
    checked = set()
    for role in LEGACY_ROLES:
        for action in definition.stage(role)["actions"]:
            clip = definition.clip(role, action)
            path = root / clip["atlas"].lstrip("/")
            if path in checked:
                continue
            checked.add(path)
            if not path.is_file() or not path.resolve().is_relative_to(root):
                raise ValueError("Missing content or escaped source: " + str(path))
            from PIL import Image
            with Image.open(path) as image:
                if not 1 <= image.height <= 240 or image.width != image.height * clip["frames"]:
                    raise ValueError("Content atlas does not match declared frames: " + str(path))
        portrait = root / definition.stage(role)["portrait"].lstrip("/")
        if not portrait.is_file() or not portrait.resolve().is_relative_to(root):
            raise ValueError("Missing content portrait: " + str(portrait))
    for field in ("background", "background_night"):
        path = root / definition.document[field].lstrip("/")
        if not path.is_file() or not path.resolve().is_relative_to(root):
            raise ValueError("Missing content background: " + str(path))


def python_module(definition):
    return ('"""Generated by scripts/content_definitions.py; edit src/data/content/firemon.json."""\n'
            + "BUILTIN_CONTENT = " + pprint.pformat(definition.document, width=100, sort_dicts=True) + "\n")


def cpp_header(definition, namespace="builtin_content", function="builtinDefinition"):
    quote = lambda value: json.dumps(value, ensure_ascii=True)
    lines = ["// Generated by scripts/content_definitions.py. Do not edit.", "#pragma once",
             "namespace vpet { namespace content { namespace " + namespace + " {"]
    for role in LEGACY_ROLES:
        for context in CONTEXTS:
            lines.append("static constexpr Clip %s_%s[] = {" % (role, context))
            for action in ACTIONS:
                clip = definition.clip(role, action, context)
                lines.append("    {%s,%d,%d,%d,%d,%d}," % (quote(clip["path"]), clip["frames"],
                             clip["interval_ms"], *clip["loop"], clip["canvas"]))
            lines.append("};")
        stage = definition.stage(role)
        values = [stage.get("motion_overrides", {}).get(a,
                  [definition.clip(role, a)["frames"], definition.clip(role, a)["interval_ms"]]) for a in ACTIONS]
        for index, key in enumerate(("frames", "intervals")):
            lines.append("static constexpr uint16_t %s_motion_%s[] = {%s};" %
                         (role, key, ",".join(str(v[index]) for v in values)))
    lines.append("static constexpr Stage stages[] = {")
    for role in LEGACY_ROLES:
        stage = definition.stage(role)
        lines.append("    {%s,%s,%s,%s,{%s},%s_motion_frames,%s_motion_intervals}," %
                     (quote(stage["name"]), quote(stage["short_name"]), quote(stage["battle_name"]),
                      quote(stage["portrait_asset"]), ",".join(role + "_" + c for c in CONTEXTS), role, role))
    lines += ["};", "static constexpr PetDefinition definition = {%s,%s,%s,%s,stages};" %
              tuple(quote(definition.document[key]) for key in ("id", "version", "background_asset", "background_night_asset")),
              "}", "inline const PetDefinition& %s() { return %s::definition; }" % (function, namespace), "} }", ""]
    return "\n".join(lines)


def export(root=ROOT, check=False):
    definition = load_definition()
    rule_python = ('"""Generated by scripts/content_definitions.py; edit src/data/digimon/*.json."""\n'
                   + "EVOLUTION_REGISTRY = " + pprint.pformat(rules_registry(), width=100, sort_dicts=True) + "\n")
    for relative, source in ((HEADER, cpp_header(definition)), (PYTHON, python_module(definition)),
                             (RULE_HEADER, rules_header()), (RULE_PYTHON, rule_python)):
        target = Path(root) / relative
        if check:
            if not target.is_file() or target.read_text() != source:
                raise ValueError("Outdated content artifact: " + str(relative))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    export(check=parser.parse_args().check)
