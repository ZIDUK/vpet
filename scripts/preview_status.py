"""Generate deterministic previews of the four Status pages (1/4 vital,
2/4 care, 3/4 battle, 4/4 DNA) for the T-Display 240x135 simulator.

Outputs land in ``out/status-preview/``:

* ``status-1-4-{es,en}.png`` — vital (HP de crianza, alimentación,
  energía, ánimo) with differentiated bars (red/orange/cyan/green).
* ``status-2-4-{es,en}.png`` — care (edad, sobrealimentaciones,
  errores de cuidado, esfuerzo, batallas, lesiones).
* ``status-3-4-{es,en}.png`` — battle (peso, DP, %victorias,
  proteína, W-L).
* ``status-4-4-{es,en}.png`` — DNA (código completo XX-XX-XX-XX,
  hélice rotando, seis stats con barras 0..99 y EV).
* ``status-overview-{es,en}.png`` — 4x1 grid of the four pages.
* ``status-helix.gif`` — animated GIF of the DNA page rendering
  across one full helix spin period (2400 ms), generated by
  sampling the real renderer at deterministic timestamps.

The script does NOT mutate the pet state (the renderer never
writes back, the snapshot is taken before any frame and the pet
byte-for-byte equals its initial state after the script returns).
"""
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "src")]

from PIL import Image

from core.pet import Pet, STATE_LIVE
from display_profiles import get_display_profile
from scripts import build as build_script
from scripts.sim_renderer import render_frame


def _build_pet(language):
    """A live rookie with realistic status values so all four pages
    have non-trivial content (age in minutes, some overfeeds, mixed
    battle record, EV across several stats). The pet is built fresh
    per language so the snapshots are independent."""
    pet = Pet(species="rookie", state=STATE_LIVE)
    pet.language = language
    pet.stats["hp"] = 85
    pet.stats["h"] = 60
    pet.stats["e"] = 40
    pet.stats["p"] = 75
    pet.injuries = 2
    pet.stage_age_seconds = 7200  # 2h
    pet.overfeeds = 3
    pet.care_mistakes = 1
    pet.effort = 50
    pet.battles_this_form = 7
    pet.weight = 6
    pet.dp = 2
    pet.battles_won = 7
    pet.battles_lost = 3
    pet.protein = 2
    pet.restore_dna((0xAB, 0xCD, 0xEF, 0x12))
    pet.restore_ev({"hp": 18, "mp": 0, "off": 24, "def": 12, "spd": 6,
                     "brn": 0})
    return pet


def _capture(output, build_dir, language):
    """Render the four pages plus an overview sheet for one language."""
    profile = get_display_profile("tdisplay")
    pet = _build_pet(language)
    lang = language.lower()
    snapshot = pet.to_dict()

    frames = {}
    for page in range(4):
        frame = render_frame(
            build_dir,
            pet,
            menu_index=0,
            panel_mode="status",
            panel_index=page,
            profile=profile,
            pet_x=140,
            now_ms=0,
        )
        path = output / ("status-%d-4-%s.png" % (page + 1, lang))
        frame.save(path)
        frames[page] = frame
        # The pet must be byte-for-byte unchanged after the render.
        assert pet.to_dict() == snapshot, (
            "renderer mutated the pet on page %d" % page)

    # 4x1 overview.
    overview = Image.new("RGB", (960, 135))
    for page in range(4):
        overview.paste(frames[page], (page * 240, 0))
    overview.resize((1920, 270), Image.Resampling.NEAREST).save(
        output / ("status-overview-%s.png" % lang))
    conditions = Image.new("RGB", (720, 135))
    for index, (dead, injured) in enumerate(((False, False), (False, True), (True, True))):
        pet.dead, pet.injured = dead, injured
        condition = render_frame(build_dir, pet, menu_index=0, panel_mode="status",
                                 panel_index=1, profile=profile, now_ms=0)
        conditions.paste(condition, (index * 240, 0))
    conditions.resize((1440, 270), Image.Resampling.NEAREST).save(
        output / ("status-conditions-%s.png" % lang))
    return frames


def _capture_helix_gif(output, build_dir, language="EN"):
    """Sample the DNA page at deterministic timestamps across one full
    helix spin (2400 ms) and stitch the frames into a GIF. The
    pet is restored between frames so the byte-for-byte invariant
    holds throughout."""
    profile = get_display_profile("tdisplay")
    pet = _build_pet(language)
    snapshot = pet.to_dict()
    frames = []
    # 24 frames at 100 ms steps covers one full spin.
    steps = 24
    period_ms = 2400
    for index in range(steps):
        now_ms = int(index * (period_ms / steps))
        frame = render_frame(
            build_dir,
            pet,
            menu_index=0,
            panel_mode="status",
            panel_index=3,
            profile=profile,
            pet_x=140,
            now_ms=now_ms,
        )
        frames.append(frame.convert("P", palette=Image.ADAPTIVE,
                                     colors=64))
    # Restore the pet between every frame to make the invariant
    # explicit; the renderer must never write back regardless.
    assert pet.to_dict() == snapshot
    gif_path = output / ("status-helix-%s.gif" % language.lower())
    frames[0].save(gif_path, save_all=True, append_images=frames[1:],
                    duration=int(period_ms / steps), loop=0)
    return gif_path


def main():
    output = ROOT / "out" / "status-preview"
    output.mkdir(parents=True, exist_ok=True)
    build_dir = ROOT / "build-tdisplay"
    if not build_dir.exists():
        # Fallback: build into a temp dir but warn the caller.
        import tempfile
        with tempfile.TemporaryDirectory() as tmp:
            tmp_build = Path(tmp) / "build-tdisplay"
            build_script.main(profile_name="tdisplay",
                                output_dir=tmp_build)
            for lang in ("ES", "EN"):
                _capture(output, tmp_build, lang)
                _capture_helix_gif(output, tmp_build, lang)
        return
    for lang in ("ES", "EN"):
        _capture(output, build_dir, lang)
        _capture_helix_gif(output, build_dir, lang)
    print(output / "status-overview-es.png")
    print(output / "status-helix-es.gif")
    print(output / "status-helix-en.gif")


if __name__ == "__main__":
    main()
