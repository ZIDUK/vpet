"""Package the approved Training artwork, copy and bitmap fonts for C++."""
import json

from PIL import Image, ImageDraw, ImageFont

from scripts.practice_icons import info_icon, technique_icon
from scripts.tdisplay_assets import write_asset
from src.core.i18n import TRAINING_STRINGS, STAT_STRINGS


def package_training(sim_build, data_dir, include_dir):
    records = []

    def asset(name, frames):
        records.append(write_asset(data_dir / "training" / (name + ".vpa"),
                                   frames, frames[0].size))

    sprite_sets = {
        "egg": ("Egg", "egg", {"idle": "idle"}),
        "sparkmon": ("Baby", "sparkmon", {"idle": "idle", "walk": "walk", "eat": "eat"}),
        "firemon": ("Rookie", "firemon", {"idle": "idle", "punch": "punch", "block": "block", "walk": "walk", "cast": "cast"}),
        "flamemon": ("Champion", "flamemon", {"idle": "idle", "punch": "punch", "block": "cast", "walk": "walk", "cast": "cast"}),
        "dragfiremon": ("Ultimate", "dragfiremon", {"idle": "idle", "punch": "punch", "block": "cast", "walk": "fly", "cast": "cast"}),
    }
    for pet_name, (stage, filename, actions) in sprite_sets.items():
        for action, source_action in actions.items():
            source = sim_build / "digimon1" / stage / f"{filename}_{source_action}_atlas.bmp"
            with Image.open(source) as atlas:
                frames = []
                for x in range(0, atlas.width, atlas.height):
                    cell = atlas.crop((x, 0, x + atlas.height, atlas.height))
                    alpha = cell.point([0] + [255] * 255, mode="L")
                    cell = cell.convert("RGBA")
                    cell.putalpha(alpha)
                    frames.append(cell.resize((68, 68), Image.Resampling.NEAREST))
                asset(f"{pet_name}_{action}", frames)

    for action in ("idle", "punch", "block", "walk", "cast"):
        with Image.open(sim_build / "digimon1/Rookie" / f"firemon_{action}_atlas.bmp") as atlas:
            frames = []
            for x in range(0, atlas.width, atlas.height):
                cell = atlas.crop((x, 0, x + atlas.height, atlas.height))
                alpha = cell.point([0] + [255] * 255, mode="L")
                cell = cell.convert("RGBA")
                cell.putalpha(alpha)
                frames.append(cell.resize((68, 68), Image.Resampling.NEAREST))
            asset(action, frames)
    for name in ("Training", "Pedia", "Back"):
        with Image.open(sim_build / "UIIcons" / (name + ".bmp")) as icon:
            asset(name.lower(), [icon.convert("RGBA").resize((16, 16), Image.Resampling.NEAREST)])
    for name in ("punch", "flame", "guard"):
        asset("tech_" + name, [technique_icon(name)])
    for name in ("power", "cost", "mastery", "training", "lock"):
        asset(name + "10", [info_icon(name, 10)])
    for name in ("attack", "defense", "speed", "hp", "mp", "mind"):
        for size in (10, 16):
            asset(f"{name}{size}", [info_icon(name, size)])

    lines = ["// Generated by scripts/training_assets.py. Do not edit.",
             "#pragma once", "#include <stdint.h>", "#include <string.h>",
             "namespace vpet { namespace training_assets {",
             "struct Glyph { uint8_t advance; uint8_t top; uint8_t rasterTop; uint16_t rows[16]; };" ]
    for size in (9, 10):
        font = ImageFont.load_default(size=size)
        lines.append(f"static const Glyph font{size}[] = {{")
        for code in range(32, 127):
            glyph = Image.new("1", (200, 16))
            draw = ImageDraw.Draw(glyph)
            draw.fontmode = "1"
            # A fixed ascent prevents FreeType's per-string monochrome bearing
            # rounding from changing the baseline of an isolated glyph.
            prefix = "A            "
            origin = 2 + int(font.getlength(prefix, mode="1"))
            draw.text((2, 0), prefix + chr(code) + "            i|^", font=font, fill=1)
            glyph = glyph.crop((origin - 2, 0, origin + 14, 16))
            rows = [sum(int(glyph.getpixel((x, y))) << x for x in range(16)) for y in range(16)]
            advance = font.getlength(chr(code), mode="1")
            if advance != int(advance):
                raise ValueError("Training requires integer bitmap font advances")
            top = font.getbbox(chr(code), mode="1")[1]
            isolated = Image.new("1", (16, 16))
            isolated_draw = ImageDraw.Draw(isolated)
            isolated_draw.fontmode = "1"
            isolated_draw.text((2, 0), chr(code), font=font, fill=1)
            raster_top = top
            if glyph.getbbox() and isolated.getbbox():
                raster_top += glyph.getbbox()[1] - isolated.getbbox()[1]
            lines.append("{%d,%d,%d,{%s}}," % (advance, top, raster_top, ",".join(map(str, rows))))
        lines.append("};")
    lines += ["struct Copy { const char* key; const char* es; const char* en; };",
              "static const Copy strings[] = {"]
    strings = {k: v for k, v in TRAINING_STRINGS.items() if k.startswith("training.")}
    strings.update({"stat." + k: v for k, v in STAT_STRINGS.items()})
    for key, value in sorted(strings.items()):
        lines.append("{%s,%s,%s}," % tuple(json.dumps(s) for s in (key, value["ES"], value["EN"])))
    lines += ["};", "inline const char* copy(const char* key, bool es) {",
              "  for (const auto& item : strings) if (strcmp(item.key,key)==0) return es ? item.es : item.en;",
              "  return key;", "}", "}}"]
    (include_dir / "TrainingArtwork.h").write_text("\n".join(lines) + "\n")
    return records
